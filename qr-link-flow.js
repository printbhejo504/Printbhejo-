/* PrintBhejo QR auto-connect flow.
   QR images are generated by App.jsx with an exact active-session URL.
   Do not rewrite the QR image through a third-party QR service: doing so
   would discard the session id and can break permanent/temporary QR routing. */
(() => {
  function triggerScanFlow() {
    const params = new URLSearchParams(window.location.search);
    if (params.get("scan") !== "1") return;

    const pin = (params.get("pin") || "").trim().toUpperCase();
    const session = (params.get("session") || "").trim();

    // App.jsx owns the actual WebRTC connect logic. This script only
    // normalizes the URL state and provides a fast fallback event.
    if (session || pin) {
      window.__printbhejoQrScan = { session, pin };
      window.dispatchEvent(new CustomEvent("printbhejo:qr-scan", {
        detail: { session, pin }
      }));
    }
  }

  triggerScanFlow();
})();
